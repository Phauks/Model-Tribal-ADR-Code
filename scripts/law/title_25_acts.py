MONTH = r"(?:Jan|Feb|Mar|Apr|May|June|July|Aug|Sept|Oct|Nov|Dec)\.? \d{1,2}, \d{4}"
# One Act in a citation: a public law ("Pub. L. 93-638, ..., 88 Stat. 2203") or a dated Act
# ("June 18, 1934, ch. 576, ..., 48 Stat. 984", also "act June 18, 1934, ..." in notes).
PUBLIC_LAW = re.compile(r"Pub\. L\. (\d+)-(\d+)\b[^;()]*?(\d+) Stat\. (\d+)")
DATED = re.compile(r"(?:\bact |\bAct |joint resolution |J\. Res\. |^|; )(" + MONTH + r"), (?:ch\. ([0-9A-Z]+)|No\. (\d+)|Res\. No\. (\d+)|Pub\. Res\. No\. (\d+))?[^;()]*?(\d+) Stat\. (\d+)")
GONE = re.compile(r"^(Repealed|Transferred|Omitted|Renumbered|Vacant|Reserved)\b", re.I)
NATIVE = re.compile(r"\b(Indian|Indians|Tribe|Tribes|Tribal|tribe|tribes|tribal|Native|Alaska|Hawaiian|Eskimo|Aleut|Reservation|reservation|Pueblo|Rancheria|Navajo|Hopi|Cherokee|Choctaw|Chickasaw|Creek|Seminole|Osage|Sioux|Apache|Ute|Menominee|Klamath|Band of|Nation)\b")
MONTH_NUMBERS = {name.rstrip("."): index + 1 for index, name in enumerate(MONTHS)}
MONTH_NUMBERS.update({"Sept": 9, "Sep": 9})


def text_of(fragment: str) -> str:
    plain = html.unescape(re.sub(r"<[^>]+>", " ", fragment)).replace("–", "-").replace("\xa0", " ")
    return re.sub(r"\s+", " ", plain).strip()


def iso(date: str) -> str:
    month, day, year = re.match(r"([A-Za-z]+)\.? (\d{1,2}), (\d{4})", date).groups()
    return f"{year}-{MONTH_NUMBERS[month]:02d}-{int(day):02d}"


def cites(text: str) -> list[dict]:
    """Each Act a citation string names, in order."""
    found = []
    for match in PUBLIC_LAW.finditer(text):
        date = re.search(MONTH, match.group(0))
        found.append((match.start(), {"law": f"{match.group(1)}-{match.group(2)}", "volume": match.group(3), "page": match.group(4),
                                      **({"date": iso(date.group(0))} if date else {})}))
    for match in DATED.finditer(text):
        if re.search(r"Pub\. L\. [\d-]+,[^;]*$", text[max(0, match.start() - 60):match.start()]):
            continue  # the date inside a public law citation
        number = match.group(2) or match.group(3) or match.group(4) or match.group(5) or ""
        kind = "ch" if match.group(2) else ("res" if (match.group(4) or match.group(5)) else ("no" if match.group(3) else ""))
        found.append((match.start(), {"date": iso(match.group(1)), "kind": kind, "number": number,
                                      "volume": match.group(6), "page": match.group(7)}))
    return [entry for _, entry in sorted(found, key=lambda pair: pair[0])]


def act_id(cite: dict) -> str:
    if "law" in cite:
        return f"pl:{cite['law']}"
    return f"act:{cite['date']}:{cite['kind']}{cite['number']}" if cite["number"] else f"act:{cite['date']}:{cite['volume']}-{cite['page']}"


def code_sections(page: str) -> list[dict]:
    """Every section of the Code's Title 25, with its source credit and the Acts behind it."""
    sections = []
    for block in re.split(r"(?=<!-- documentid:25_)", page)[1:]:
        head = re.search(r'<h3 class="section-head">(.*?)</h3>', block)
        chapter = re.search(r"itempath:/250/CHAPTER ([0-9A-Z]+)", block)
        if not head or not chapter:
            continue
        match = re.match(r"§+\s*([^.]+?)\.\s*(.*)$", text_of(head.group(1)))
        if not match:
            continue
        number, heading = match.group(1).strip(), match.group(2).strip()
        pdf_page = re.search(r"documentPDFPage:(\d+)", block)
        credit = re.search(r'<p class="source-credit">(.*?)</p>', block, re.S)
        credit_text = text_of(credit.group(1)).strip("() .") if credit else ""
        roles: list[tuple[dict, str]] = []
        live = not GONE.match(heading)
        for index, cite in enumerate(cites(credit_text)):
            roles.append((cite, "enacted" if index == 0 and live else "amended"))
        body, _, notes = block.partition("<!-- field-start:notes")
        if not live:
            for cite in cites(heading):
                roles.append((cite, "repealed"))
            described = text_of(body.split("</h3>", 1)[-1])
            for chunk in re.split(r"(?=\bSections? \d)", described):
                for index, cite in enumerate(cites(chunk)):
                    roles.append((cite, "enacted-former" if index == 0 else "amended"))
        for kind, note in re.findall(r'<h4 class="note-head">(Short Title[^<]*|Prior Provisions)</h4>(.*?)(?=<h4|<!-- field-end:notes)', notes, re.S):
            for chunk in re.split(r"(?=\b(?:A prior|Prior|Section|Sections) )", text_of(note)) if kind == "Prior Provisions" else [text_of(note)]:
                for index, cite in enumerate(cites(chunk)):
                    roles.append((cite, "short-title" if kind.startswith("Short") else ("enacted-former" if index == 0 else "amended")))
        names = []
        enacting = next((cite for cite, role in roles if role == "enacted"), None)
        for note in re.findall(r'<h4 class="note-head">Short Title[^<]*</h4>(.*?)(?=<h4|<!-- field-end:notes)', notes, re.S):
            for sentence in re.split(r"(?<=[.”\"])\s+(?=Pub\. L\.|Act |act |[A-Z][a-z]{2,4}\.? \d)", text_of(note)):
                for named in re.finditer(r"(?:cited as|known as)(?: the)? ([\"'“‘])(.+?)\1(?=[\s.,;\"”\]]|$)", sentence):
                    found = cites(sentence)
                    act = act_id(found[0]) if found else (act_id(enacting) if enacting and "enacted this section" in sentence else None)
                    if not act:
                        continue
                    part = re.search(r"provided that (?:title|subtitle|part|div|section|chapter)\b|\bThis (?:title|subtitle|part|division|chapter)\b", sentence)
                    names.append({"act": act, "name": named.group(2).strip(" ,."), "whole": not part})
        sections.append({"chapter": chapter.group(1), "number": number, "heading": heading, "live": live,
                         "credit": credit_text, "pdf_page": int(pdf_page.group(1)) if pdf_page else None,
                         "roles": [{"act": act_id(cite), "cite": cite, "role": role} for cite, role in roles], "names": names})
    return sections


def chapter_first_pages(page: str) -> dict[str, int]:
    """The page of the whole title's PDF each chapter starts on, to find a section inside the chapter's own PDF."""
    first = {}
    for match in re.finditer(r"<!-- documentid:25_-ch([0-9A-Z]+) [^>]*?documentPDFPage:(\d+)", page):
        first.setdefault(match.group(1), int(match.group(2)))
    return first


def regulation_sections() -> dict[str, list[dict]]:
    structure = json.loads(get(f"{ECFR}/structure/current/title-25.json"))
    parts: dict[str, list[dict]] = {}

    def walk(node: dict, part: str | None) -> None:
        if node.get("type") == "part":
            part = node["identifier"]
            parts.setdefault(part, [])
        if node.get("type") == "section" and part:
            parts[part].append({"number": node["identifier"], "heading": (node.get("label_description") or "").strip(),
                                "reserved": bool(node.get("reserved"))})
            return
        for child in node.get("children") or []:
            walk(child, part)

    walk(structure, None)
    return parts


def resolve(cite: dict) -> str:
    """The GovInfo granule holding the cited page of the Statutes at Large: STATUTE-48-Pg984."""
    result = subprocess.run(["curl", "-gsIL", "-m", "90", "-A", "Mozilla/5.0", "-o", "/dev/null", "-w", "%{http_code} %{url_effective}",
                             f"https://www.govinfo.gov/link/statute/{cite['volume']}/{cite['page']}"], capture_output=True, text=True)
    code, _, final = result.stdout.partition(" ")
    match = re.search(r"/(STATUTE-\d+-Pg[0-9A-Z-]+)\.pdf", final)
    return match.group(1) if code == "200" and match else ""


def probe(granule: str) -> bool:
    """Whether GovInfo has this granule of the Statutes at Large."""
    package = granule.split("-Pg")[0]
    result = subprocess.run(["curl", "-gsL", "-m", "60", "-A", "Mozilla/5.0", "-o", "/dev/null", "-w", "%{http_code} %{url_effective}",
                             f"https://www.govinfo.gov/metadata/granule/{package}/{granule}/mods.xml"], capture_output=True, text=True)
    return result.stdout.startswith("200 ") and result.stdout.endswith("/mods.xml")


def granule_metadata(granule: str) -> dict:
    package = granule.split("-Pg")[0]
    page = get(f"https://www.govinfo.gov/metadata/granule/{package}/{granule}/mods.xml")

    def first(pattern: str) -> str:
        match = re.search(pattern, page, re.S)
        return html.unescape(match.group(1)).strip() if match else ""

    return {
        "granule": granule,
        "title": re.sub(r"\s+", " ", first(r"<mods[^>]*>.*?<titleInfo>\s*<title>(.*?)</title>")),
        "short_titles": sorted({html.unescape(t).strip() for t in re.findall(r'<shortTitle[^>]*>(.*?)</shortTitle>', page)}),
        "start": first(r'<extent unit="pages">\s*<start>(.*?)</start>'),
        "end": first(r'<extent unit="pages">\s*<start>.*?</start>\s*<end>(.*?)</end>'),
        "public_law": first(r'<identifier type="public law citation">Public Law (\d+-\d+)</identifier>'),
        "chapter": first(r"<chapter>(.*?)</chapter>"),
        "class": first(r"<granuleClass>(.*?)</granuleClass>"),
        "congress": first(r"<congress>(.*?)</congress>"),
    }


def fetch(args) -> None:
    work = Path(args.work)
    (work / "acts").mkdir(parents=True, exist_ok=True)
    cache_path = work / "granules.json"
    cache = json.loads(cache_path.read_text()) if cache_path.exists() else {}
    year, page = latest_code_edition()
    sections = code_sections(page)
    first_pages = chapter_first_pages(page)
    acts: dict[str, dict] = {}
    for section in sections:
        for entry in section["roles"]:
            act = acts.setdefault(entry["act"], {"id": entry["act"], "cite": entry["cite"], "roles": {}, "names": [], "dates": []})
            if entry["cite"].get("date") and entry["cite"]["date"] not in act["dates"]:
                act["dates"].append(entry["cite"]["date"])
            act["roles"].setdefault(entry["role"], []).append(section["number"])
        for name in section["names"]:
            if name["act"] in acts and name not in acts[name["act"]]["names"]:
                acts[name["act"]]["names"].append({"name": name["name"], "whole": name["whole"]})

    def look_up(act: dict) -> None:
        key = f"{act['cite']['volume']}/{act['cite']['page']}"
        if key not in cache:
            granule = resolve(act["cite"])
            try:
                cache[key] = granule_metadata(granule) if granule else {}
            except RuntimeError:
                act["granule"] = {}  # not cached, so the next run tries again
                return
        act["granule"] = cache[key]

    with ThreadPoolExecutor(4) as pool:
        list(pool.map(look_up, acts.values()))
    cache_path.write_text(json.dumps(cache, indent=1))

    # A page of the Statutes at Large can hold the end of one Act and the start of several more; GovInfo's link
    # answers with the first of them. Where that granule's chapter or public law number is not the one cited, try
    # the others that start on the page (STATUTE-25-Pg612-2, -3, ...) and on the pages before it (an Act can run for many pages before the cited one).
    def correct(act: dict) -> None:
        if not act["granule"] or not check_granule(act):
            return
        key = f"{act['cite']['volume']}/{act['cite']['page']}#{act['id']}"
        if key not in cache:
            cache[key] = {}
            volume, page = act["cite"]["volume"], int(act["cite"]["page"])
            for start in range(page, max(page - 40, 0), -1):
                for suffix in ["", *(f"-{n}" for n in range(2, 9))]:
                    granule = f"STATUTE-{volume}-Pg{start}{suffix}"
                    if not probe(granule):
                        break
                    candidate = granule_metadata(granule)
                    if not check_granule({**act, "granule": candidate}):
                        cache[key] = candidate
                        break
                if cache[key]:
                    break
        if cache[key]:
            act["granule"] = cache[key]

    with ThreadPoolExecutor(2) as pool:
        list(pool.map(correct, acts.values()))
    cache_path.write_text(json.dumps(cache, indent=1))
    # One record per granule: the same Act can be cited by date and chapter in one place and by its public law number in another.
    by_granule: dict[str, dict] = {}
    # An Act whose citation names another Act's pages joins that Act; it never names the record.
    for act in sorted(acts.values(), key=lambda act: bool(check_granule(act))):
        granule = act["granule"].get("granule")
        act["include"] = bool({"enacted", "enacted-former", "short-title"} & set(act["roles"])) or bool(
            NATIVE.search(act["granule"].get("title", "") + " " + " ".join(act["granule"].get("short_titles", []))))
        act["check"] = check_granule(act)
        if granule and granule in by_granule:
            kept = by_granule[granule]
            for role, numbers in act["roles"].items():
                kept["roles"].setdefault(role, []).extend(numbers)
            kept["names"] += [name for name in act["names"] if name not in kept["names"]]
            kept["also"] = kept.get("also", []) + [act["id"]]
            kept["include"] = kept["include"] or act["include"]
            act["merged_into"] = kept["id"]
        elif granule:
            by_granule[granule] = act
    for act in by_granule.values():
        if not act["include"]:
            continue
        path = work / "acts" / f"{act['granule']['granule']}.pdf"
        if not path.exists():
            package = act["granule"]["granule"].split("-Pg")[0]
            try:
                get(f"{GOVINFO}/{package}/pdf/{act['granule']['granule']}.pdf", path)
            except RuntimeError:
                act["pdf_failed"] = True
            time.sleep(0.2)
    RAW.parent.mkdir(parents=True, exist_ok=True)
    RAW.write_text(json.dumps({
        "generated": dt.date.today().isoformat(),
        "code": {"edition": year, "source": f"{GOVINFO}/USCODE-{year}-title25/html/USCODE-{year}-title25.htm",
                 "chapter_first_pages": first_pages, "sections": sections},
        "regulations": {"source": f"{ECFR}/structure/current/title-25.json", "parts": regulation_sections()},
        "acts": sorted(acts.values(), key=lambda act: act["id"]),
    }, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    write_review(acts)
    included = [act for act in by_granule.values() if act["include"]]
    print(f"{len(sections)} sections; {len(acts)} Act citations, {len(by_granule)} granules, {len(included)} Acts included, "
          f"{sum(1 for act in acts.values() if not act['granule'])} not resolved, {sum(1 for act in acts.values() if act['check'])} to check")


def check_granule(act: dict) -> str:
    """Whether the granule is the Act the citation names: its public law or chapter number must match."""
    granule, cite = act["granule"], act["cite"]
    if not granule:
        return "no GovInfo granule for the cited page"
    if granule.get("class") and granule["class"] not in ("PUBLICLAW", "PRIVATELAW"):
        return f"granule is a {granule['class'].lower()}, not a law"
    if "law" in cite:
        return "" if granule.get("public_law") == cite["law"] else f"granule is Pub. L. {granule.get('public_law') or 'unknown'}, cited Pub. L. {cite['law']}"
    if cite["kind"] == "ch" and granule.get("chapter") and granule["chapter"] != cite["number"]:
        return f"granule is ch. {granule['chapter']}, cited ch. {cite['number']}"
    return ""


def write_review(acts: dict[str, dict]) -> None:
    REVIEW.parent.mkdir(parents=True, exist_ok=True)
    with REVIEW.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.writer(handle)
        writer.writerow(["act", "granule", "included", "roles", "title", "check", "merged_into"])
        for act in sorted(acts.values(), key=lambda act: act["id"]):
            writer.writerow([act["id"], act["granule"].get("granule", ""), "yes" if act.get("include") else "no",
                             "; ".join(f"{role} {len(numbers)}" for role, numbers in sorted(act["roles"].items())),
                             act["granule"].get("title", "")[:160], act.get("check", ""), act.get("merged_into", "")])



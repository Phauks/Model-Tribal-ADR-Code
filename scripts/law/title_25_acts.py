def existing_acts() -> dict[str, str]:
    """Existing whole-Act statute records, by public law number ("pl:93-638") and by Statutes at Large start page ("48/984")."""
    found: dict[str, str] = {}
    for path in sorted(SOURCES.glob("*/*.yaml")):
        text = path.read_text(encoding="utf-8")
        if "kind: federal-statute" not in text or GENERATED in text:
            continue
        record = yaml.safe_load(text)
        key = record["key"]
        if re.search(r"(^usc-|^us-code-|^united-states-code|section|title-[ivx]+|-amendment)", key):
            continue  # a section or a part of an Act, not the whole Act
        citation = record.get("citation") or {}
        joined = " ".join(str(citation.get(field) or "") for field in ("number", "title-short", "container-title"))
        for law in re.findall(r"Pub\. L\. (?:No\. )?(\d+-\d+)", joined) + re.findall(r"^public-law-(\d+-\d+)$", key):
            found.setdefault(f"pl:{law}", key)
        if citation.get("volume") and citation.get("page"):
            found.setdefault(f"{citation['volume']}/{citation['page']}", key)
        for volume, page in re.findall(r"(\d+) Stat\. (\d+)", joined):
            found.setdefault(f"{volume}/{page}", key)
    return found


def stored_copies() -> dict[str, dict]:
    copies = {}
    for row in csv.DictReader(INDEX.open(encoding="utf-8")):
        match = re.search(r"(STATUTE-\d+-Pg[0-9A-Z-]+)\.pdf$", row["key"])
        if match and row["key"].startswith("govinfo/"):
            copies[match.group(1)] = {"storage_key": row["key"], "checksum": row["sha256"],
                                      "media_type": row["media_type"], "bytes": int(row["bytes"])}
    return copies


def add_file_block(path: Path, block: dict) -> bool:
    """Give an existing record its stored copy, when it has none."""
    text = path.read_text(encoding="utf-8")
    if "\nfile:\n" in text or "\nrights:\n" not in text:
        return False
    text = text.replace("\nrights:\n", "\n" + dump({"file": block}) + "rights:\n", 1)
    text = re.sub(r"\nfound_in:\n((?:- .*\n)+)", lambda m: f"\nfound_in:\n{m.group(1)}- {SESSION}\n", text, count=1)
    path.write_text(text, encoding="utf-8")
    return True


def act_key(act: dict) -> str:
    cite = act["cite"]
    if "law" in cite:
        return f"public-law-{cite['law']}"
    date = cite["date"]
    if cite["kind"] == "res":
        return f"joint-resolution-{date}-no-{cite['number']}"
    if cite["number"]:
        return f"act-{date}-{'ch' if cite['kind'] == 'ch' else 'no'}-{cite['number'].lower()}"
    return f"act-{date}-{cite['volume']}-stat-{cite['page']}"


def act_name(act: dict, same_day: int) -> tuple[str, str]:
    """The Act's name and its long title. The name is the one Title 25 or GovInfo gives the whole Act, else "Act of <date>"."""
    granule = act["granule"]
    long_title = granule.get("title", "")
    whole = [name["name"] for name in act["names"] if name["whole"]]
    # GovInfo's title is the Act's name when it reads as one ("Indian Self-Determination and Education Assistance Act"),
    # not when it is the long title ("An Act To conserve ...", "Making appropriations for ...").
    official = long_title if long_title and re.search(r"\b(Act|Amendments|Code)\b", long_title) and not re.match(
        r"(an act|a bill|joint resolution|a joint resolution|an ordinance|resolution|making|regarding|to |for |authoriz|provid|relating)", long_title, re.I) else ""
    if whole:
        name = whole[0]
    elif official:
        name = official
    elif len(granule.get("short_titles", [])) == 1:
        name = granule["short_titles"][0]
    else:
        name = ""
    if not name:
        cite = act["cite"]
        date = long_date(act["date"]) if act.get("date") else ""
        if "law" in cite:
            name = f"Act of {date}" if date else f"Pub. L. No. {cite['law']}"
        else:
            noun = "Joint Resolution" if cite["kind"] == "res" else "Act"
            name = f"{noun} of {date}" + (f", ch. {cite['number']}" if same_day > 1 and cite["kind"] == "ch" else "")
    if long_title == name:
        long_title = ""
    return name, long_title.rstrip(".")


def act_date(act: dict, sections: dict[str, dict]) -> str:
    """The Act's date: from its citation, or for a public law, from the source credits that cite it."""
    if act["cite"].get("date"):
        return act["cite"]["date"]
    for other in act.get("dates", []):
        return other
    for numbers in act["roles"].values():
        for number in numbers:
            credit = sections.get(number, {}).get("credit", "")
            match = re.search(r"Pub\. L\. " + re.escape(act["cite"]["law"]) + r"\b[^;]*?(" + MONTH + r")", credit)
            if match:
                return iso(match.group(1))
    return ""


def act_record(act: dict, name: str, long_title: str, copy: dict | None, enacted: list[str], former: list[str]) -> dict:
    cite, granule = act["cite"], act["granule"]
    volume, start = granule["granule"].split("-")[1], granule["start"] or cite["page"]
    date = act["date"]
    year = int(date[:4]) if date else None
    link = f"https://www.govinfo.gov/app/details/STATUTE-{volume}/{granule['granule']}"
    number = f"Pub. L. No. {cite['law']}" if "law" in cite else (
        f"ch. {cite['number']}" if cite["kind"] == "ch" else (f"Pub. Res. No. {cite['number']}" if cite["kind"] == "res" else (f"No. {cite['number']}" if cite["number"] else "")))
    citation = {"type": "legislation", "title": long_title or name}
    if long_title:
        citation["title-short"] = name
    citation.update({"container-title": "United States Statutes at Large", "volume": volume, "page": start})
    if number:
        citation["number"] = number
    citation["author"] = [{"literal": "United States Congress"}]
    citation["URL"] = link
    if date:
        citation["issued"] = {"date-parts": [[int(part) for part in date.split("-")]]}
    citation["accessed"] = {"date-parts": [[2026, 11, 26]]}
    record = {"key": act_key(act), "kind": "federal-statute", "citation": citation,
              "original_link": link, "retrieved": "2026-11-26", "archives": []}
    if copy:
        record["file"] = copy
    record["rights"] = RIGHTS
    record["jurisdictions"] = [{"level": "federal"}]
    record["found_in"] = [SESSION]
    unnamed = name.startswith(("Act of ", "Joint Resolution of ", "Pub. L. No. "))
    pin = f"{volume} Stat. {start}"
    if unnamed:
        indigo = f"{name}, {number + ', ' if number and number not in name else ''}{pin}"
    else:
        indigo = f"{name}, {number + ', ' if number else ''}{pin}{f' ({year})' if year and str(year) not in name else ''}"
    pages = f"{granule['start']}-{granule['end']}" if granule.get("start") and granule.get("end") and granule["start"] != granule["end"] else start
    sections_line = ""
    if enacted:
        sections_line += f" Enacted {len(enacted)} section{'s' if len(enacted) != 1 else ''} of Title 25 of the United States Code in force in the 2024 edition."
    if former:
        sections_line += f" Enacted {len(former)} former section{'s' if len(former) != 1 else ''} of Title 25, since repealed, transferred or omitted."
    parts = sorted({part["name"] for part in act["names"] if not part["whole"] and part["name"] != name})
    parts_line = f" Parts of it have their own short titles: {'; '.join(parts)}." if parts else ""
    record["notes"] = (f"Indigo Book citation: {indigo}. Statutes at Large, volume {volume}, pages {pages} ({granule['granule']} on GovInfo)."
                       + sections_line + parts_line
                       + (" The stored copy is that slip of the Statutes at Large." if copy else " No copy is stored.")
                       + " Generated by scripts/law/title_25_acts.py from Title 25's source credits and notes and GovInfo's metadata; Unverified.")
    return record


def records(args) -> None:
    raw = json.loads(RAW.read_text(encoding="utf-8"))
    sections = {section["number"]: section for section in raw["code"]["sections"]}
    copies = stored_copies()
    existing = existing_acts()
    acts = {act["id"]: act for act in raw["acts"]}
    # An Act whose granule could not be matched to its chapter or public law number gets no record until checked by hand
    # (the review file lists it).
    keep = [act for act in acts.values() if act["include"] and act["granule"] and not act.get("merged_into") and not act["check"]]
    same_day: dict[str, int] = {}
    for act in keep:
        act["date"] = act_date(act, sections)
        same_day[act["date"]] = same_day.get(act["date"], 0) + 1
    target: dict[str, str] = {}  # act id -> record key
    written = linked = given = 0
    for act in keep:
        granule = act["granule"]
        existing_key = existing.get(act["id"]) or existing.get(f"{granule['granule'].split('-')[1]}/{granule['start']}")
        copy = copies.get(granule["granule"])
        enacted = sorted(set(act["roles"].get("enacted", [])))
        former = sorted(set(act["roles"].get("enacted-former", [])))
        if existing_key:
            path = next(SOURCES.glob(f"*/{existing_key}.yaml"))
            given += bool(copy and add_file_block(path, copy))
            key = existing_key
            linked += 1
        else:
            name, long_title = act_name(act, same_day.get(act["date"], 1))
            record = act_record(act, name, long_title, copy, enacted, former)
            key = record["key"]
            path = SOURCES / key[0] / f"{key}.yaml"
            if path.exists() and GENERATED not in path.read_text(encoding="utf-8"):
                sys.exit(f"key in use by another record: {key}")
            path.parent.mkdir(exist_ok=True)
            path.write_text(dump(record), encoding="utf-8")
            written += 1
        for identifier in [act["id"], *act.get("also", [])]:
            target[identifier] = key
    for act in acts.values():
        if act["check"] and act["id"] in existing and act["id"] not in target:
            target[act["id"]] = existing[act["id"]]  # unmatched on GovInfo, but already a record by its public law number
    for act in acts.values():
        if act.get("merged_into") in target:
            target[act["id"]] = target[act["merged_into"]]
    write_sections(raw, target)
    print(f"Acts: {written} records written, {linked} matched to existing records ({given} given their stored copy)")


def write_sections(raw: dict, target: dict[str, str]) -> None:
    """The section lists the chapter and part pages show: content/law/title-25-sections.json."""
    code = raw["code"]
    first = code["chapter_first_pages"]
    chapters: dict[str, list[dict]] = {}
    for section in code["sections"]:
        enacting = next((entry for entry in section["roles"] if entry["role"] in ("enacted", "enacted-former")), None)
        row = {"number": section["number"], "heading": section["heading"], "inForce": section["live"]}
        if enacting and enacting["act"] in target:
            row["act"] = target[enacting["act"]]
        if section["credit"]:
            row["credit"] = section["credit"]
        if section.get("pdf_page") and first.get(section["chapter"]):
            row["page"] = section["pdf_page"] - first[section["chapter"]] + 1
        chapters.setdefault(section["chapter"].lower(), []).append(row)
    parts = {number: [{"number": row["number"], "heading": row["heading"]} for row in rows if not row["reserved"]]
             for number, rows in raw["regulations"]["parts"].items()}
    SECTIONS.parent.mkdir(parents=True, exist_ok=True)
    SECTIONS.write_text(json.dumps({
        "note": "Generated by scripts/law/title_25_acts.py. Sections of Title 25 of the United States Code (2024 edition on GovInfo) by chapter, with the record of the Act that enacted each, and sections of 25 C.F.R. (eCFR) by part.",
        "codeEdition": code["edition"], "regulationsRead": raw["generated"],
        "code": chapters, "regulations": parts,
    }, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


def file(args) -> None:
    sys.path.insert(0, str(ROOT / "scripts/captures"))
    import mirror_captures  # noqa: E402

    raw = json.loads(RAW.read_text(encoding="utf-8"))
    have = stored_copies()
    work = Path(args.work)
    for act in raw["acts"]:
        granule = act["granule"].get("granule")
        if not act["include"] or not granule or act.get("merged_into") or granule in have:
            continue
        local = work / "acts" / f"{granule}.pdf"
        if not local.exists() or local.stat().st_size > LARGEST:
            continue  # the site serves no copy over 64 MB; the page links GovInfo's
        package = granule.split("-Pg")[0]
        mirror_captures.add(argparse.Namespace(
            captures=args.captures, files=[str(local)], topic=f"govinfo/{package}", name=f"{granule}.pdf", record="",
            obtained="downloaded from GovInfo (United States Statutes at Large) by scripts/law/title_25_acts.py",
            title=act["granule"].get("title", "")[:300], link=[f"{GOVINFO}/{package}/pdf/{granule}.pdf"], redistribution="yes",
            nations="", rights="United States government work (17 U.S.C. § 105).", keep_local=False))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = parser.add_subparsers(dest="command", required=True)
    for name in ("fetch", "file", "records"):
        p = sub.add_parser(name)
        if name in ("fetch", "file"):
            p.add_argument("--work", required=True)
        if name == "file":
            p.add_argument("--captures", required=True)
    args = parser.parse_args()
    {"fetch": fetch, "file": file, "records": records}[args.command](args)


if __name__ == "__main__":
    main()

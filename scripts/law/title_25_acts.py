#!/usr/bin/env python3
"""Source records for the Acts of Congress behind Title 25 of the United States
Code, and the section lists of Title 25 of the Code and of the Code of Federal
Regulations (data tier 1; Trevor, Nov. 24 and 26, 2026).

The chapter and part records come from scripts/law/title_25_records.py. This
script adds what sits below and behind them:

- Every section of Title 25 of the Code (2024 edition on GovInfo), with its
  heading, whether it is in force, its source credit and the Act that enacted
  it, and every section of 25 C.F.R. (eCFR structure), written to
  content/law/title-25-sections.json, which the chapter and part
  pages list and /stats counts.
- A record for each Act of Congress the Code's Title 25 draws on: the Act
  that enacted a section in force (the first Act in its source credit), the
  Act that enacted a section since repealed, transferred or omitted (from the
  section's own note or a "Prior Provisions" note), every Act a "Short Title"
  note names, and any other Act in a source credit whose official title is
  about Native nations or Native people. Acts that only amended Title 25 in
  passing (such as the Act renaming the General Accounting Office) are listed
  in the review file and get no page. An Act that already has a record keeps
  it; the sections link to that record.

Each Act's text is its slip of the United States Statutes at Large on GovInfo
(https://www.govinfo.gov/link/statute/<volume>/<page>, which answers with the
Act's own granule), stored in the bucket under
govinfo/STATUTE-<volume>/STATUTE-<volume>-Pg<page>.pdf, the folder the site's
other Statutes at Large copies use. Its name and long title come from the
granule's MODS record on GovInfo and from Title 25's own "Short Title" notes.

Steps:
  fetch    Read both titles, resolve each Act to its GovInfo granule, read the
           granule's metadata and download its PDF into --work. Writes
           research/raw/2026-11-26/title-25-acts.json and
           research/reviews/2026-11-26-title-25-acts.csv (every Act found,
           included or not, and any mismatch between the source credit and
           the granule).
  file     Store the PDFs in the bucket with scripts/captures/mirror_captures.py.
  records  Write content/sources/a/act-*.yaml, content/sources/p/public-law-*.yaml
           and content/law/title-25-sections.json; existing Act
           records without a stored copy gain it.

Usage:
  python3 scripts/law/title_25_acts.py fetch --work DIR
  python3 scripts/law/title_25_acts.py file --work DIR --captures /mnt/project-files/research/captures
  python3 scripts/law/title_25_acts.py records
"""

#!/usr/bin/env python3
"""The outline of Title 25 of the United States Code: its chapters,
subchapters, parts and sections in the Code's own order, with each section's
status, for browsing the title from the title down to a single section
(Trevor, Nov. 27, 2026: "we should make U.S. title 25 more navigable. It may
form the basis for how we organize the navigation for our model codes").

Read from the title's HTML on GovInfo, whose comments give each item's place
in the outline ("itempath: /250/CHAPTER 46/SUBCHAPTER I/Sec. 5321"), its page
in the title's PDF and the date the edition is current through. A section
that is no longer in force keeps its status and the Code's own words for it:
the law that repealed it, the section it was moved to, or why it was omitted.

Written to content/law/title-25-outline.json as one flat list in the Code's
order, so a page can find a section's chapter, subchapter, part, previous and
next by position. The same shape (levels, numbers, headings, statuses) is
meant to carry any other code's outline later.

Usage:
  python3 scripts/law/title_25_outline.py [--html FILE]
"""
from __future__ import annotations

import argparse
import html
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from title_25_records import latest_code_edition  # noqa: E402

ROOT = Path(__file__).resolve().parents[2]
OUTLINE = ROOT / "content/law/title-25-outline.json"
GENERATED = "Generated by scripts/law/title_25_outline.py"
GONE = re.compile(r"^(Repealed|Transferred|Omitted|Renumbered|Vacant|Reserved)\b\.?\s*", re.I)
SMALL = {"a", "an", "and", "as", "at", "by", "for", "in", "of", "on", "or", "the", "to", "with", "from", "under", "into", "upon"}
ROMAN = re.compile(r"^[IVXL]+(?:-[A-Z])?$")
LEVEL = {"chapter-head": "chapter", "subchapter-head": "subchapter", "part-head": "part"}


def title_case(text: str) -> str:
    """'INDIAN SELF-DETERMINATION AND EDUCATION ASSISTANCE' as 'Indian Self-Determination and Education Assistance'."""
    words = []
    for index, word in enumerate(text.split()):
        lower = word.lower()
        if ROMAN.match(word.strip("[](),;:")):
            words.append(word)
        elif index > 0 and lower in SMALL:
            words.append(lower)
        else:
            words.append("-".join(part[:1].upper() + part[1:] for part in lower.split("-")))
    return " ".join(words)


def plain(fragment: str) -> str:
    return re.sub(r"\s+", " ", html.unescape(re.sub(r"<[^>]+>", "", fragment))).strip()


def status_note(status: str, rest: str, body: str) -> tuple[str | None, str | None]:
    """The Code's own words for a section no longer in force, and the section it moved to."""
    moved = None
    found = re.search(r"(?:reclassified as|transferred to|merged into) section (\S+?) of (this title|title (\d+))", body)
    if found:
        moved = found.group(1) if found.group(2) == "this title" else f"{found.group(3)} U.S.C. § {found.group(1)}"
    if rest:
        return rest.rstrip("."), moved
    codification = re.search(r'<h4 class="note-head">Codification</h4>\s*<p class="note-body">(.*?)</p>', body, re.S)
    if codification:
        return plain(codification.group(1)), moved
    return None, moved


def outline(page: str, year: int) -> dict:
    through = re.search(r"currentthrough:(\d{8})", page)
    items = []
    for document in re.split(r"(?=<!-- documentid:)", page):
        path = re.search(r"<!-- itempath:(.*?) -->", document)
        head = re.search(r'<h3 class="(section-head|chapter-head|subchapter-head|part-head)">(.*?)</h3>', document, re.S)
        if not path or not head:
            continue
        page_number = re.search(r"documentPDFPage:(\d+)", document)
        kind, text = head.group(1), plain(head.group(2))
        if kind in LEVEL:
            label, _, name = text.partition("—")
            number = label.strip("[] ").split(" ", 1)[1] if " " in label.strip("[] ") else label
            items.append({"level": LEVEL[kind], "number": number.replace("–", "-"), "heading": title_case(name.strip("[] ")) if name else "", **({"page": int(page_number.group(1))} if page_number else {})})
            continue
        found = re.match(r"(§§?)\s*([^.]+)\.\s*(.*)", text)
        if not found:
            raise ValueError(f"unexpected section head: {text}")
        number = found.group(2).replace("–", "-").strip()
        heading = found.group(3).strip()
        gone = GONE.match(heading)
        row = {"level": "section", "number": number, "heading": heading, "status": "in force"}
        if found.group(1) == "§§":
            row["range"] = True
        if gone:
            status = gone.group(1).lower()
            row["status"] = "moved" if status == "transferred" else status
            note, moved = status_note(status, heading[gone.end():].strip(), document)
            row["heading"] = gone.group(1).capitalize()
            if note:
                row["note"] = note
            if moved:
                row["movedTo"] = moved
        if page_number:
            row["page"] = int(page_number.group(1))
        items.append(row)
    return {
        "note": f"{GENERATED} from the {year} edition of Title 25 on GovInfo.",
        "source": f"https://www.govinfo.gov/content/pkg/USCODE-{year}-title25/html/USCODE-{year}-title25.htm",
        "edition": year,
        "currentThrough": f"{through.group(1)[:4]}-{through.group(1)[4:6]}-{through.group(1)[6:]}" if through else None,
        "title": {"number": "25", "heading": "Indians"},
        "items": items,
    }


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--html", type=Path, help="A copy of the title's HTML already downloaded, and its edition year as --year")
    parser.add_argument("--year", type=int)
    args = parser.parse_args()
    if args.html:
        year, page = args.year or int(re.search(r"USCODE-(\d{4})", args.html.read_text(encoding="utf-8")).group(1)), args.html.read_text(encoding="utf-8")
    else:
        year, page = latest_code_edition()
    data = outline(page, year)
    OUTLINE.write_text(json.dumps(data, ensure_ascii=False, indent="\t") + "\n", encoding="utf-8")
    counts: dict[str, int] = {}
    for item in data["items"]:
        key = item["level"] if item["level"] != "section" else f"section ({item['status']})"
        counts[key] = counts.get(key, 0) + 1
    print(f"wrote {OUTLINE.relative_to(ROOT)}: " + ", ".join(f"{count} {key}" for key, count in counts.items()))


if __name__ == "__main__":
    main()

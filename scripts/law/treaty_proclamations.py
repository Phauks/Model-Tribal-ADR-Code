"""Record the day each ratified treaty was ratified and proclaimed.

The President proclaims a treaty once the Senate has consented to it, so the
proclamation date tells which President's page lists it (Trevor, Nov. 27,
2026: each President's page shows what they signed). Kappler's Indian
Affairs: Laws and Treaties, vol. 2, heads each ratified treaty with the date
it was signed, its Statutes at Large citation and, for most, the dates it was
ratified and proclaimed ("Oct. 28, 1867. | 15 Stat., 593. | Ratified July 25,
1868. | Proclaimed Aug. 19, 1868."). The treaty check of Nov. 24, 2026 read
those headers from the Oklahoma State University scan of Kappler and compared
each date with the stored Statutes at Large text
(research/reviews/2026-11-24-treaty-verification-ratified.csv). This script
copies the dates from that check into content/law/treaty-proclamations.yaml,
with the result of the comparison for each.

Run from the repository root:

    python3 scripts/law/treaty_proclamations.py
"""

from __future__ import annotations

import csv
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parents[2]
CHECK = ROOT / "research" / "reviews" / "2026-11-24-treaty-verification-ratified.csv"
OUTPUT = ROOT / "content" / "law" / "treaty-proclamations.yaml"
SOURCES = ROOT / "content" / "sources"


def dated(cell: str) -> tuple[str, str] | None:
    """"1868-08-12 ok (later page)" -> ("1868-08-12", "ok (later page)")."""
    match = re.fullmatch(r"(\d{4}-\d{2}-\d{2})\s*(.*)", (cell or "").strip())
    return (match.group(1), match.group(2).strip()) if match else None


def main() -> int:
    treaties: list[dict] = []
    for row in csv.DictReader(CHECK.open(encoding="utf-8")):
        proclaimed = dated(row["proclaimed"])
        if not proclaimed:
            continue
        key = row["key"]
        if row["date_signed"] and proclaimed[0] < row["date_signed"]:
            # A misprinted year that Kappler corrects in brackets: "Proclamation Jan. 15, 1319 [1819]."
            fixed = re.search(r"\[(\d{4})\]\.?\s*$", row["kappler_header"])
            if not fixed:
                raise SystemExit(f"{key}: proclaimed {proclaimed[0]}, before it was signed ({row['date_signed']})")
            proclaimed = (fixed.group(1) + proclaimed[0][4:], proclaimed[1])
        if row["date_signed"] and int(proclaimed[0][:4]) - int(row["date_signed"][:4]) > 30:
            # Read as a misprint, not a date: "June 25, 1817 | 7 Stat., 155. | Proclamation, Dec. 26,1877."
            print(f"left out {key}: proclaimed {proclaimed[0]}, {row['date_signed']} signed", file=sys.stderr)
            continue
        if not (SOURCES / key[0] / f"{key}.yaml").exists():
            raise SystemExit(f"{CHECK.name} names {key}, which has no record in content/sources")
        entry: dict = {"key": key, "signed": row["date_signed"] or None}
        ratified = dated(row["ratified"])
        if ratified:
            entry["ratified"] = ratified[0]
        entry["proclaimed"] = proclaimed[0]
        # "ok": the stored Statutes at Large text has the same date; "not found": it does not print it.
        entry["text_check"] = proclaimed[1] or None
        entry["kappler_header"] = row["kappler_header"]
        treaties.append(entry)
    treaties.sort(key=lambda entry: (entry["proclaimed"], entry["key"]))
    header = (
        "# Generated by scripts/law/treaty_proclamations.py from the treaty check of Nov. 24, 2026\n"
        "# (research/reviews/2026-11-24-treaty-verification-ratified.csv), which read Kappler's headers.\n"
        "# Do not edit by hand.\n"
    )
    document = {
        "source": "kappler-indian-affairs-laws-and-treaties-vol-2-1904",
        "treaties": treaties,
    }
    OUTPUT.write_text(header + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=1000), encoding="utf-8")
    print(f"{len(treaties)} treaties with a proclamation date", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())

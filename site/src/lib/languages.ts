/**
 * Languages a person may list on their profile (docs/contributor-profiles.md, "Languages").
 *
 * The Native languages of North America, and the languages of Hawai‘i and the Pacific
 * Islands of the United States, are the U.S. Census Bureau’s American Community Survey
 * Language Code List (2024), codes 6800 to 7099 and 3220 to 3570, with the
 * ISO 639-3 code the list gives for each: U.S. Census Bureau, American Community Survey
 * Language Code List (Feb. 3, 2025),
 * https://www2.census.gov/programs-surveys/demo/about/language-use/primary_language_list.pdf.
 * The two collective entries, "Athapascan languages" (ath) and "Iroquoian languages" (iro), are
 * left out because each names a family, not a language. Names are the list’s own.
 * Sign languages carry their ISO 639-3 codes from the registration authority, SIL International,
 * https://iso639-3.sil.org/code_tables/639/data, because the survey counts only spoken languages.
 *
 * `keywords` are other names a reader might type, often the language’s name for itself. They are
 * searched but never shown, so a name missing here costs only a search.
 */

export interface LanguageChoice {
	/** The ISO 639-3 code, which is what a profile stores. */
	code: string;
	name: string;
	group: LanguageGroup;
	/** The Census Bureau code, where the survey has one. */
	censusCode?: number;
	keywords?: string[];
}


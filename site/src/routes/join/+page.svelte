	<h2>How registering works</h2>
	<ol>
		<li>
			<strong>Sign in</strong> with your email address. We email you a code; your account is made the
			first time, and you can choose a password later. We use the sign-in only to know it is you.
		</li>
		<li>
			<strong>Tell us about yourself</strong>: your name, how to reach you, any Native nation you want
			to name, your background, and how you would like to help. Only your name is required.
		</li>
		<li>
			<strong>Choose your credit</strong>: by name, by name and nation, by a description, by a name you
			choose, or not at all; in the book, on the website, or both.
		</li>
		<li>
			<strong>Check your answers</strong> on one page that shows who can see each one and your credit
			exactly as it will be printed, then confirm.
		</li>
		<li>
			<strong>The lead author replies</strong>, and gives workspace access to people who will review or
			write.
		</li>
	</ol>
	<p>You can change your answers, or delete your profile, at any time.</p>

	<h2>Your information</h2>
	<ul>
		<li>Only the lead author and editors see your profile. Nothing is published except the credit you confirm.</li>
		<li>Your email address and phone number are never printed or published.</li>
		<li>
			Naming a Native nation is optional and is never checked. We do not ask for enrollment numbers or
			proof, and listing a nation does not mean you speak for it.
		</li>
		<li>
			Registering does not give permission to use anything you share. Stories, interviews and documents
			each get their own contributor statement, where you decide how they may be used.
		</li>
	</ul>


	<h1>Help write the code</h1>
	<p class="lead">
		People help by writing, reviewing drafts, finding sources, translating, making art and sharing
		what they know.
	</p>

	<h2>How it works</h2>
	<ol>
		<li><strong>Sign in</strong> with your email address. We send you a code. You can set a password later.</li>
		<li>
			<strong>Tell us about yourself</strong>: your name, how to reach you, and how you would like to
			help. Only your name is required.
		</li>
		<li>
			<strong>Choose your credit</strong>: your name, your name and nation, a description, a name you
			choose, or none. In the book, on the website, or both.
		</li>
		<li><strong>Check and confirm.</strong> You see your credit exactly as it will be printed.</li>
		<li><strong>The lead author replies</strong> and gives reviewers and writers access to drafts.</li>
	</ol>

	<h2>Your information</h2>
	<ul>
		<li>Only the lead author and editors see your profile. Only your confirmed credit is published.</li>
		<li>Your email address and phone number are never published.</li>
		<li>Naming a Native nation is optional. We never ask for proof, and naming one does not mean you speak for it.</li>
		<li>
			Signing up is not permission to use what you share. Stories, interviews and documents each get
			their own consent form, on the <a href="/forms">Forms</a> page.
		</li>
		<li>You can change your answers or delete your profile at any time.</li>
	</ul>

